/**
 * Query 改写(任务 #28)
 *
 * 把口语化问题转成语义标准化的检索查询,提升 RAG 召回率。
 *
 * 策略:
 *   1. 词典映射:口语词 → KB 术语(规则版,零成本)
 *   2. 领域关键词补全:根据 domain 自动补相关术语
 *   3. 去除噪声词:删除口语填充词("我"、"请问"、"帮我看看")
 *
 * 设计目标:不依赖 LLM 调用,纯本地规则,在几毫秒内完成。
 */

(function () {
  'use strict';

  // 口语 → KB 术语映射
  const COLLOQUIAL_MAP = [
    // 八字
    [/(我老公|丈夫|老婆|妻子|伴侣)/g, '配偶'],
    [/(男朋友|女友|对象)/g, '配偶'],
    [/(小孩|孩子|儿子|女儿|宝宝)/g, '子女'],
    [/(我爸|父亲|老爹|我爹)/g, '父亲'],
    [/(我妈|母亲|老娘|我娘)/g, '母亲'],
    [/(出轨|搞外遇|有小三|劈腿|外遇)/g, '桃花 咸池 配偶宫'],
    [/(破财|亏钱|赔钱|漏财)/g, '财星受损 比劫夺财'],
    [/(发财|赚大钱|暴富|横财)/g, '偏财 财运'],
    [/(升职|升官|当官|做官|提拔)/g, '官杀 事业'],
    [/(工作不顺|失业|被炒|找不到工作)/g, '事业 受克'],
    [/(考学|高考|考研|考公|考试)/g, '文昌 印星 学业'],
    [/(生病|得病|住院|癌症|绝症)/g, '健康 疾厄宫'],
    [/(死亡|寿命|能活多久|寿元)/g, '寿命 疾厄'],

    // 六爻
    [/(求财|赚钱|生意|买卖|投资)/g, '财爻 妻财'],
    [/(能不能成|会不会成|能否成功)/g, '成与不成 应期'],
    [/(东西丢|找东西|寻物|失物)/g, '寻物 应爻'],
    [/(官司|打官司|诉讼|被告)/g, '官鬼 世应'],

    // 奇门
    [/(出门|远行|出差|旅行)/g, '出行 九天 远行'],
    [/(谈判|谈判|谈合作)/g, '谈判 合作 六合'],

    // 通用
    [/(请帮我|请看看|帮我分析|帮我看看|请帮我看看)/g, ''],
    [/(想问问|想问一下|想了解|请问)/g, ''],
    [/(到底|究竟|到底是不是|到底会不会)/g, ''],
    [/(的)?(运势|运程|命运)/g, '运程 命局'],
    [/(怎么样|好不好|行不行|如何|怎样)/g, '']
  ];

  // 各 domain 自动补充的关键词(扩展查询覆盖面)
  const DOMAIN_BOOST = {
    bazi:   ['日主', '十神', '用神', '大运', '流年', '格局'],
    ziwei:  ['命宫', '身宫', '迁移宫', '财帛宫', '官禄宫', '夫妻宫'],
    liuyao: ['世爻', '应爻', '用神', '原神', '忌神', '伏神', '动爻'],
    qimen:  ['天盘', '地盘', '九星', '八门', '八神', '用神宫'],
    cross:  ['三术对照', '交叉验证', '用神一致'],
    fengshui: ['宅卦', '命卦', '方位', '布局', '五行'],
    xingshi: ['人格', '地格', '总格', '三才'],
    shouxiang: ['主线', '掌型', '丘'],
    mianxiang: ['五官', '三停', '十二宫'],
    daofo:  ['化解', '符箓', '咒语', '手诀']
  };

  // 移除噪声词
  const NOISE_REGEX = /[?？!！。.,，\s]+/g;

  /**
   * 改写查询
   * @param {string} query 用户原始问题
   * @param {string} domain 占卜流派
   * @returns {string} 改写后的检索查询
   */
  function rewriteQuery(query, domain) {
    if (!query) return '';
    let q = query;

    // 1. 词典映射
    for (const [pattern, replacement] of COLLOQUIAL_MAP) {
      q = q.replace(pattern, replacement);
    }

    // 2. 提取核心关键词(去噪声)
    const tokens = q.split(NOISE_REGEX).filter(Boolean);

    // 3. 合并 domain boost(只取前 3 个,避免污染)
    const boost = (DOMAIN_BOOST[domain] || []).slice(0, 3);

    // 4. 组合
    const finalQuery = [...new Set([...tokens, ...boost])].join(' ');

    // 5. 限制长度(避免过长)
    return finalQuery.slice(0, 200);
  }

  window.QueryRewrite = { rewriteQuery, COLLOQUIAL_MAP, DOMAIN_BOOST };
})();