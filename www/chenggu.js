var CG_CN_NUM = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
var CG_MONTH_CN = ['', '正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '冬', '腊'];
var CG_DAY_CN = ['',
  '初一', '初二', '初三', '初四', '初五', '初六', '初七', '初八', '初九', '初十',
  '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十',
  '廿一', '廿二', '廿三', '廿四', '廿五', '廿六', '廿七', '廿八', '廿九', '三十'
];

// 钱数 → 中文(如 36 → '三两六钱', 40 → '四两', 7 → '七钱')
function cgQianToText(qian) {
  var liang = Math.floor(qian / 10);
  var q = qian % 10;
  var text = '';
  if (liang > 0) text += CG_CN_NUM[liang] + '两';
  if (q > 0) text += CG_CN_NUM[q] + '钱';
  if (!text) text = '零钱';
  return text;
}

// 农历引擎获取(与 liuyao.js getSolarEngine 同模式)
function cgGetSolarEngine() {
  var Solar = (typeof window !== 'undefined' && window.Solar) || (typeof globalThis !== 'undefined' && globalThis.Solar);
  if (!Solar && typeof window !== 'undefined' && typeof window.getYearGZEx === 'function') {
    // Node 测试环境下由 ganzhi.js 的高精度加载器把本地 lunar.bundle.js 挂到 globalThis
    window.getYearGZEx(2000, 1, 1);
    Solar = window.Solar || (typeof globalThis !== 'undefined' && globalThis.Solar);
  }
  if (!Solar || typeof Solar.fromDate !== 'function') {
    throw new Error('农历引擎未加载，无法换算称骨所需农历');
  }
  return Solar;
}

function cgAssertInt(value, min, max, label) {
  if (typeof value !== 'number' || isNaN(value) || Math.floor(value) !== value || value < min || value > max) {
    throw new Error(label + '必须是 ' + min + '~' + max + ' 的整数');
  }
}

/**
 * 按农历分量直接称骨(可测试的核心)
 * input: { yearGZ: '甲子', month: 1~12, day: 1~30, hourZhi: '子' }
 * 闰月: 调用方传入正数月份即可(按当月算, 见文件头注释)
 */
function chengguSuanByLunar(input) {
  input = input || {};
  var yearGZ = input.yearGZ;
  if (typeof yearGZ !== 'string' || CG_YEAR_WEIGHT[yearGZ] === undefined) {
    throw new Error('无效的年干支: ' + yearGZ + '(须为六十甲子之一)');
  }
  cgAssertInt(input.month, 1, 12, '农历月');
  cgAssertInt(input.day, 1, 30, '农历日');
  var hourZhi = input.hourZhi;
  if (typeof hourZhi !== 'string' || CG_HOUR_WEIGHT[hourZhi] === undefined) {
    throw new Error('无效的时支: ' + hourZhi + '(须为子丑寅卯辰巳午未申酉戌亥之一)');
  }

  var wYear = CG_YEAR_WEIGHT[yearGZ];
  var wMonth = CG_MONTH_WEIGHT[input.month];
  var wDay = CG_DAY_WEIGHT[input.day];
  var wHour = CG_HOUR_WEIGHT[hourZhi];
  var total = wYear + wMonth + wDay + wHour;
  var verdict = CG_VERDICTS[total];
  if (!verdict) throw new Error('总骨重 ' + cgQianToText(total) + ' 超出称骨歌范围(二两一~七两二)');

  return {
    method: '袁天罡称骨',
    lunar: {
      yearGZ: yearGZ,
      month: input.month,
      monthCN: CG_MONTH_CN[input.month] + '月',
      day: input.day,
      dayCN: CG_DAY_CN[input.day],
      isLeapMonth: !!input.isLeapMonth,
      hourZhi: hourZhi
    },
    weights: {
      year: { label: yearGZ + '年', qian: wYear, text: cgQianToText(wYear) },
      month: { label: CG_MONTH_CN[input.month] + '月', qian: wMonth, text: cgQianToText(wMonth) },
      day: { label: CG_DAY_CN[input.day], qian: wDay, text: cgQianToText(wDay) },
      hour: { label: hourZhi + '时', qian: wHour, text: cgQianToText(wHour) }
    },
    totalQian: total,
    totalText: cgQianToText(total),
    verdict: { title: verdict.t, male: verdict.m, female: verdict.f }
  };
}

/**
 * 公历日期称骨: dt → lunar-javascript 转农历 → 查表求和 → 断语
 * 年干支按立春换年(lunar.getYearInGanZhi() 默认即是)
 */
function chengguSuan(dt) {
  if (!(dt instanceof Date) || isNaN(dt.getTime())) {
    throw new Error('无效的出生时间');
  }
  var lunar = cgGetSolarEngine().fromDate(dt).getLunar();
  var rawMonth = lunar.getMonth(); // 负数表示闰月
  var pan = chengguSuanByLunar({
    yearGZ: lunar.getYearInGanZhi(),
    month: Math.abs(rawMonth),
    day: lunar.getDay(),
    hourZhi: lunar.getTimeZhi(),
    isLeapMonth: rawMonth < 0
  });
  pan.solar = dt.getFullYear() + '年' + (dt.getMonth() + 1) + '月' + dt.getDate() + '日 ' +
    dt.getHours() + ':' + String(dt.getMinutes()).padStart(2, '0');
  return pan;
}

// 组装给 AI 的确定性事实 prompt (重量与断语为代码定论, AI 不可更改)
function formatChengguPrompt(pan, question) {
  var text = '【袁天罡称骨算命】\n';
  if (pan.solar) text += '公历:' + pan.solar + '\n';
  text += '农历:' + pan.lunar.yearGZ + '年' + (pan.lunar.isLeapMonth ? '闰' : '') + pan.lunar.monthCN +
    pan.lunar.dayCN + ' ' + pan.lunar.hourZhi + '时\n';
  text += '\n四柱骨重明细(代码定论,不可更改):\n';
  text += '  年:' + pan.weights.year.label + ' = ' + pan.weights.year.text + '\n';
  text += '  月:' + pan.weights.month.label + ' = ' + pan.weights.month.text + '\n';
  text += '  日:' + pan.weights.day.label + ' = ' + pan.weights.day.text + '\n';
  text += '  时:' + pan.weights.hour.label + ' = ' + pan.weights.hour.text + '\n';
  text += '  总骨重:' + pan.totalText + '(' + pan.totalQian + '钱)\n';
  if (pan.verdict.title) text += '\n命格:' + pan.verdict.title + '\n';
  text += '\n称骨歌(断语为代码定论,不可更改):\n';
  text += '  男命:' + pan.verdict.male + '\n';
  text += '  女命:' + pan.verdict.female + '\n';
  if (question) text += '\n所问之事:' + question + '\n';
  return text;
}

